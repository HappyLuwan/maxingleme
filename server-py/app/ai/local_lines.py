def extract_tags(user_input: str) -> List[str]:
    """
    从用户输入中提取标签（多个可叠加）
    简单包含关系匹配，命中即计一个 tag
    """
    if not user_input:
        return ["general"]
    text = user_input.lower()
    hit: list[str] = []
    for tag, keywords in KEYWORD_TAG_MAP.items():
        for kw in keywords:
            if kw.lower() in text:
                hit.append(tag)
                break  # 同一 tag 命中一次即可
    return hit if hit else ["general"]


