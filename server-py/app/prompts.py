# ---------- 注册中心 ----------
# 注意：CUSTOM 风格不需要 Prompt（不匹配文案库，直接原样返回用户输入）
_REGISTRY: Dict[RoastStyle, Prompt] = {
    RoastStyle.YIJU: YIJU_PROMPT,
    RoastStyle.YINYANG: YINYANG_PROMPT,
    RoastStyle.WENROU: WENROU_PROMPT,
    RoastStyle.LUXUN: LUXUN_PROMPT,
    RoastStyle.ZHEXUE: ZHEXUE_PROMPT,
}


def get_prompt(style: RoastStyle) -> Prompt:
    """按风格获取 Prompt，找不到返回默认 YIJU"""
    return _REGISTRY.get(style, YIJU_PROMPT)


def registered_styles() -> list[RoastStyle]:
    return list(_REGISTRY.keys())
